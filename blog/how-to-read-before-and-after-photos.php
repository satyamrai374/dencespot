<p>Every hair restoration clinic in Gurgaon sells partly on photographs, this one included. You cannot try surgery before buying it, so a picture is the closest thing to evidence anyone can hand you across a consultation desk. It is also the easiest thing on a website to manipulate without telling a lie.</p>

<p>Almost none of what follows requires editing software. Each technique happens before the shutter opens — with a lamp, a chair, a comb, and a decision about which day to take the second photograph. Spotting them will not make you cynical about surgery. It will make you harder to sell to.</p>

<h2 id="lighting-does-most-of-the-work">Lighting does most of the work</h2>

<p>Overhead light is the cruellest light there is for a thinning scalp. A ceiling spot throws each hair's shadow straight down onto the skin and lights the scalp itself, so every gap between hairs reads as bare skin. It is why hotel bathrooms show you a version of yourself you do not recognise.</p>

<p>Soft light from the front does the opposite. A large window, a diffused flash or a ring light wraps around the hair, kills the shadows and flattens the contrast between dark hair and pale scalp. The density has not changed by a single follicle. The photograph has changed completely.</p>

<p>So a clinic that shoots the <em>before</em> under a bare consultation-room downlight and the <em>after</em> beside a window has produced a transformation without performing one.</p>

<h3>What to look for</h3>

<ul>
  <li>Shadow direction under the nose, the ears and the brow. If shadows fall straight down in one image and sideways in the other, the lighting was not matched.</li>
  <li>A shine on the scalp in one image and none in the other.</li>
  <li>Different backgrounds or wall tones. If the room changed, the light changed with it.</li>
</ul>

<h2 id="camera-angle-and-head-tilt">Camera angle and head tilt</h2>

<p>The second lever is geometry. Photograph someone from above with the chin tucked down and you are looking along the top of the scalp — the surface with the least hair and the most visible skin. Shoot the same head from slightly below with the chin level and the top of the scalp leaves the frame, while the hairline appears to sit lower against the brow.</p>

<p>A pair shot that way suggests a hairline has advanced by a centimetre when nothing was transplanted at all, which is why <a href="/blog/natural-hairline-design-explained">where a hairline is placed and how it is angled</a> should be assessed in person rather than from a screen.</p>

<p>Check whether the ears sit at the same height in both frames and whether the background sits at the same level above the head. A credible gallery uses a fixed camera position and a marked spot on the floor, so the pair looks mechanically identical apart from the hair.</p>

<h2 id="wet-flat-hair-versus-dry-styled-hair">Wet, flat hair versus dry, styled hair</h2>

<p>Wet hair clumps into strands and separates, exposing the scalp between them. That is why your hair looks thinnest in the shower, and it makes a genuinely useful standardisation — wet hair hides nothing. The problem is when only one of the pair is wet.</p>

<p>A wet, combed-flat <em>before</em> against a dry, blow-dried, product-lifted <em>after</em> is a large visual change with no biological change behind it. Both photographs should be dry and styled alike, or both wet. Mixed pairs are not comparisons.</p>

<h2 id="hair-length-colour-and-concealer-products">Hair length, colour and concealer products</h2>

<p>Length is the simplest confound of all. Longer hair lies over thinner areas and covers them; a close crop reveals everything underneath. A shaved <em>before</em> taken on the morning of surgery against three months of growth afterwards is not a fair pair, however honest both images are otherwise.</p>

<p>Colour matters for contrast rather than volume. Dark hair against pale scalp is the highest-contrast combination there is, so it shows thinning most severely. Lightening the hair, grey coming through, or a tinted scalp all reduce that contrast and read as fuller hair.</p>

<p>Then there are the products. Keratin fibres, root sprays and pressed powders are effective, entirely legitimate, and impossible to tell apart from real density in a still photograph. Watch for a flat, grainy uniformity along the parting, a hairline that stops at an unnaturally hard edge, and hair that looks matted rather than separated. If a gallery does not say no concealer was used, you cannot rule one out.</p>

<h2 id="the-interval-nobody-states">The interval nobody states</h2>

<p>The most important caption is the one most galleries omit: how long after surgery the second image was taken. Transplanted hair sheds within the first month and regrows over the following year, so the same head looks different at three months, at eight and at twelve. The <a href="/blog/hair-transplant-growth-timeline-month-by-month">month-by-month account of what actually grows when</a> explains why a result cannot be judged early.</p>

<p>An image labelled "after 4 months" is a progress photograph, not an outcome. One with no interval should be read as whichever timing flatters the clinic most, because you cannot know otherwise. A gallery that states an interval for every case is doing what most here do not.</p>

<h2 id="procedure-day-photographs-are-not-results">Procedure-day photographs are not results</h2>

<p>This is the one worth learning to spot before any other, because it is endemic here — particularly in short video clips.</p>

<p>Immediately after placement, the recipient area is packed with implanted follicles, each still carrying a short cut hair. It looks dense and dark against the bare scalp photographed an hour earlier. Within two to four weeks most of those hairs fall out — a normal part of <a href="/blog/shedding-and-shock-loss-after-hair-transplant">the shedding phase after surgery</a> — and the follicles rest underneath.</p>

<p>A procedure-day photograph is genuinely informative. It shows graft distribution, hairline design and the density the surgeon actually placed. What it cannot show is a result, because nothing has grown yet. Presented as an <em>after</em>, it is the single most misleading image in this industry.</p>

<h3>How to recognise one</h3>

<ul>
  <li>Redness across the recipient area, and pinpoint crusts at each graft site.</li>
  <li>A wet or glistening look to the scalp.</li>
  <li>Uniform, very short stubble with no styling and no growth direction.</li>
  <li>The same shirt, the same room and the same day as the <em>before</em> beside it.</li>
</ul>

<p>This site carries one such image, labelled as the day of surgery rather than as an outcome, for exactly that reason. Apply the same test to <a href="/hair-transplant-results-gurgaon">the before-and-after cases published here</a> as strictly as you apply it anywhere else.</p>

