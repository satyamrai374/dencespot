<h2 id="the-angles-that-go-missing">The angles that go missing</h2>

<p>What a gallery leaves out is often more informative than what it includes. Three omissions recur.</p>

<h3>The crown</h3>

<p>Frontal photographs are flattering and easy. The crown is a whorl that consumes grafts quickly and is hardest to make look dense. A gallery with no top-down views usually means the crown was not treated, or did not fill as hoped — often a consequence of how <a href="/blog/donor-area-limits-hair-transplant">a finite donor supply has to be budgeted</a>, but you should be told.</p>

<h3>The temples</h3>

<p>Recession at the temples is a defining feature of male pattern loss (<a href="https://dermnetnz.org/topics/male-pattern-hair-loss" rel="noopener nofollow" target="_blank">DermNet: male pattern hair loss</a>), and it is exactly what a straight-on frontal image conceals. Ask for profiles on both sides, and read them against <a href="/blog/norwood-scale-explained">the Norwood stage the patient started from</a>.</p>

<h3>The donor area</h3>

<p>The most conspicuous omission. Over-harvesting shows at the back and sides as patchy, moth-eaten thinning once the hair is cut short, and it is largely permanent. A gallery with no donor area photographed at short length is avoiding the question — raise it directly, alongside the other <a href="/blog/questions-to-ask-hair-transplant-consultation">questions that test a clinic before you pay</a>.</p>

<h2 id="checking-a-gallery-for-yourself">Checking a gallery for yourself</h2>

<p>Save an image and run it through Google Lens or TinEye. If the same pair turns up on clinics in four cities and on a stock library, it is marketing material, not a patient of the clinic showing it to you. Run that check on <a href="/gallery">any set of clinic photographs</a>, including these. Look too for cropped watermarks and one face under two case numbers.</p>

