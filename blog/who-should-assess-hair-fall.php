<h2 id="dermatologists">What a dermatologist is</h2>

<p>A dermatologist in India is a medical doctor who, after the MBBS degree, has completed postgraduate training in Dermatology, Venereology and Leprosy: an MD, a DNB, or an older postgraduate diploma in the same subject. Hair, nails and the scalp are part of that training, so hair fall is ordinary dermatology work rather than a niche.</p>

<p>Like any doctor, a dermatologist must be registered with the National Medical Commission or a state medical council, and that registration is public. The postgraduate qualification is recorded against the entry, so it can be checked rather than taken on trust.</p>

<p>Other doctors matter too. A general physician can investigate and treat iron deficiency, thyroid disease and other conditions behind hair fall, and a gynaecologist or endocrinologist is often involved where PCOS or another hormonal cause is suspected. Hair fall is sometimes the visible sign of something that needs treating in its own right.</p>

<h2 id="trichologists">What "trichologist" does and does not mean in India</h2>

<p>Trichology, the study of hair and scalp, is a legitimate area of interest. The title is where care is needed. Trichology is not a recognised medical specialty in India: there is no National Medical Commission recognised postgraduate qualification in it, and "trichologist" is not a protected title. Anyone can use it, whatever training they have had, from a short course upwards.</p>

<p>Some people who call themselves trichologists are doctors who have added training in hair. Others have no medical qualification. Both may give sensible advice about hair care, but only the first can diagnose a medical condition or prescribe a prescription medicine, and the title alone does not tell you which you are seeing.</p>

<p>So ask two questions, politely and before you pay for a package: what is your qualification, and are you a registered medical practitioner? A registered doctor can give you a registration number to check. If the answer is that no doctor is involved, you know what kind of advice you are getting.</p>

<h2 id="salons-and-scalp-scans">What a salon, or a salon scalp scan, can and cannot do</h2>

<p>A good stylist sees your hair more often than anyone else, and is often the first to notice a widening parting or a thinning crown. That is genuinely useful. A salon can also help by changing what may be making things worse: tight ponytails and braids that pull on the hairline, repeated heat styling, or harsh chemical treatments that break the shafts.</p>

<p>What a salon cannot do is find the cause. Many offer a computerised scalp scan or "hair analysis", which is a magnified camera image of the scalp. It can show flaking, redness or a mix of thick and thin hairs, and it can be a good prompt to seek advice. It cannot tell iron deficiency from thyroid disease, or pattern hair loss from shedding after an illness. Hair mineral analysis is not a reliable way to detect deficiencies either; blood tests are.</p>

<p>Be wary of any setting where the assessment and the product for sale come from the same counter. A scan that always ends with a course of treatments is a sales step, whoever runs it.</p>

<h2 id="when-to-see-a-doctor">When hair fall needs a doctor rather than a product</h2>

<p>Some hair fall settles by itself. Shedding that follows a fever, a crash diet, surgery or childbirth often eases over a few months, as <a href="/blog/telogen-effluvium-vs-pattern-hair-loss">telogen effluvium and pattern hair loss</a> explains. But see a doctor, rather than trying products first, if any of these apply:</p>

<ul>
  <li>Heavy shedding that has gone on for more than a couple of months.</li>
  <li>A widening parting, a receding hairline or a thinning crown.</li>
  <li>Smooth, round bald patches, which can be alopecia areata.</li>
  <li>An itchy, scaly, red, sore or burning scalp, or pustules.</li>
  <li>Shiny, smooth skin where hair has gone and the follicle openings seem to have disappeared. Scarring hair loss is uncommon, but follicles lost to it do not come back, so it needs prompt attention.</li>
  <li>Hair fall with other symptoms: tiredness, weight change, feeling cold, irregular periods, new acne or new facial hair.</li>
  <li>Hair fall that began after starting a new medicine.</li>
  <li>Patchy, scaly hair loss in a child, which can be a fungal infection needing prescribed treatment.</li>
</ul>

