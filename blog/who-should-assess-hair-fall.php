<p>When hair starts coming out in the shower, most people try three doors, often in this order: the salon they already visit, a trichologist they found online, and eventually a doctor. Each can be useful. But they are not interchangeable, and the difference that matters is simple to state: only a registered medical practitioner can diagnose a medical cause of hair fall and prescribe medicine for it.</p>

<p>This article sets out what each option is trained to do, when hair fall needs a doctor rather than a product, and what a proper assessment actually involves. It does not argue that anyone is bad at their job. It is about asking the right person the right question.</p>

