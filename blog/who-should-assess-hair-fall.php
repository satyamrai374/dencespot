<h2 id="what-an-assessment-includes">What a medical hair fall assessment includes</h2>

<p>A proper assessment is mostly questions and looking, with tests only where they are indicated. Expect most of the following.</p>

<h3>A history</h3>

<p>When the hair fall started, whether it is shedding from all over or thinning in a pattern, and what happened two or three months beforehand: an illness such as dengue or typhoid, a pregnancy, an operation, rapid weight loss or a period of severe stress. Then your medicines and supplements, your diet, your family history, and for women, your periods and any signs of a hormonal cause.</p>

<h3>An examination</h3>

<p>The pattern of loss, the scalp skin, and a gentle pull test to see how readily hairs come away. Trichoscopy, an examination under magnification with a dermatoscope, shows variation in hair thickness, signs of inflammation and clues to specific conditions. Baseline photographs are taken so that change can be measured later rather than guessed.</p>

<h3>Blood tests, where indicated</h3>

<p>Commonly a blood count, ferritin, thyroid function, vitamin D and vitamin B12, with hormone tests for some women. Only the tests your history points to are needed; <a href="/blog/blood-tests-for-hair-fall">blood tests for hair fall</a> explains which matter and why biotin can distort some results.</p>

<h3>Occasionally, a scalp biopsy</h3>

<p>A small sample of scalp skin, taken under local anaesthetic, is sometimes needed when scarring hair loss is suspected or the diagnosis is unclear. Most people never need one.</p>

<h3>A diagnosis, a plan and a review</h3>

<p>The point of all this is a named cause and a plan matched to it: correcting a deficiency, treating a scalp condition, prescribed treatment for pattern loss, or simply reassurance and time. Progress is usually reviewed against the baseline photographs at around six months, with a fuller review at a year.</p>

