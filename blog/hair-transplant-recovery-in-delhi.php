<h2 id="back-to-work">Going back to work depends on how you get there</h2>

<p>The healing timeline is much the same for everyone. What differs across Delhi is the commute.</p>

<ul>
  <li><strong>Car or cab to a desk job:</strong> many people are back within a few days to a week, accepting some redness and crusting.</li>
  <li><strong>Metro at peak hours:</strong> a fortnight of working from home, or shifted hours, removes the crowding problem.</li>
  <li><strong>Two-wheeler:</strong> plan on about two weeks off the road, confirmed at your review.</li>
  <li><strong>Outdoor or site work:</strong> heat, dust and hard hats make a longer break, or lighter duties agreed beforehand, the realistic plan.</li>
</ul>

<p>Exercise follows its own bands: gentle walking within days (early mornings in summer, not on the worst smog days), the gym usually at around three to four weeks, swimming at around four, and anything played in a helmet only after specific clearance. Visible crusting clears for most people within ten to fourteen days, but the result is judged at around ten to twelve months, as the <a href="/blog/hair-transplant-growth-timeline-month-by-month">month-by-month growth timeline</a> explains.</p>

<h2 id="when-to-call">When to call the clinic, whatever the season</h2>

<p>Swelling, tenderness, crusting and some itching are expected. Call rather than wait if you notice any of these:</p>

<ul>
  <li>Fever, or redness and warmth that spread rather than fade.</li>
  <li>Pus or discharge, or pain that gets worse after the first few days.</li>
  <li>Bleeding that does not stop after ten minutes of gentle pressure.</li>
  <li>Swelling still spreading after about day four, or tender pustules around emerging hairs.</li>
</ul>

<p>Shedding of the transplanted hairs between roughly week two and week six is different: it is expected, as <a href="/blog/shedding-and-shock-loss-after-hair-transplant">why transplanted hairs fall out</a> explains, and <a href="/blog/hair-transplant-side-effects-and-risks">hair transplant side effects and risks</a> separates the common from the uncommon.</p>

