<p>Aftercare instructions are written for a scalp, not for a city. They tell you to keep the grafts clean, avoid pressure and stay out of the sun, and then leave you to work out what that means on an ordinary Delhi day: a cab or the Metro, a scooter and a helmet law, a June afternoon or a November morning when the sky has turned grey.</p>

<p>This article follows the first month in the order you are likely to meet each problem, starting with the journey home. None of it changes the surgery; it changes how much effort the first weeks take, and some of it is worth deciding before you choose a date. Your own written instructions come first wherever they differ from what follows.</p>

<h2 id="the-journey-home">The journey home on the day</h2>

<p>You leave with a numb, tight scalp, a dressing over the donor area and instructions not to let anything touch the recipient area. That rules out several of the cheaper ways of getting around Delhi.</p>

<ul>
  <li><strong>A car or cab driven by someone else</strong> is the simplest option. Keep the windows closed and the air conditioning on recirculation, and mind the door frame as you get in: ducking into a car is when most people first catch their head.</li>
  <li><strong>An auto-rickshaw</strong> is harder than it looks. The roof bar is low, the sides are open to dust and exhaust, and a sharp stop pitches you forward. If it is the only choice, sit well back and keep your head clear of the frame.</li>
</ul>

<p>The Metro is a poor idea on the day itself, and a two-wheeler, as rider or pillion, is off the list for now; both are covered below.</p>

<h2 id="week-one-indoors">Week one: the city stays outside your door</h2>

<p>For roughly the first ten days the grafts move from being held by little more than early clotting to being properly anchored, which is why <a href="/hair-transplant-aftercare">the aftercare guide</a> restricts pressure, friction and exertion over that window. In Delhi, the least risky version of that week is a dull one spent mostly at home, and <a href="/blog/first-14-days-after-a-hair-transplant">the first 14 days after a hair transplant</a> describes what each day usually looks like. A little planning makes it easy:</p>

<ul>
  <li>Arrange for groceries and medicines to be delivered, and agree working from home if your job allows it.</li>
  <li>Have someone with you for the first night, and sleep propped up for the first few nights. Forehead swelling commonly peaks around day three and settles on its own.</li>
  <li>Expect one necessary trip: the first wash usually falls around day three to five and is done at the clinic or demonstrated to you first. Book a cab for it, not a scooter.</li>
  <li>Leave dust that settles on the scalp for the scheduled wash. Wiping it off does more harm than the dust.</li>
</ul>

<h2 id="two-wheelers-and-helmets">Two-wheelers: the helmet problem has no workaround</h2>

<p>A large share of Delhi travels by two-wheeler, and the law requires a helmet for the pillion passenger as well as the rider. After a transplant that is the most awkward rule to live with, because a helmet does three things a healing scalp does not want: its rim drags over the hairline as it goes on, its padding presses on the grafts at the front and the donor area at the back, and it traps heat and sweat against both.</p>

<p>Riding without one is not an answer: it is illegal, and a fall on a healing scalp is far worse than a delayed return to the road. So:</p>

<ul>
  <li>Arrange other transport for about the first two weeks, or longer if the clinic advises it at your review.</li>
  <li>Count riding pillion behind a family member as riding. The helmet, and the problem, are the same.</li>
  <li>When you are cleared, ask which style of helmet suits the stage you are at, lower it on vertically rather than tugging it forward, and take it off as soon as you arrive.</li>
</ul>

<h2 id="metro-and-buses">The Metro and buses: the crowd, not the train, is the risk</h2>

<p>Nothing about a Metro coach is bad for grafts: it is air-conditioned and comparatively free of dust. The difficulty is people. At busy times a standing passenger's head sits among raised arms, grab handles and swinging bags, and a knock to a week-old recipient area is exactly the friction aftercare is designed to prevent.</p>

<ul>
  <li>For the first fortnight, travel outside rush hours if you need to travel at all.</li>
  <li>Sit if you can; if you stand, choose a spot with space around your head.</li>
  <li>Carry a backpack low and in front, so you are never lifting it over your head.</li>
</ul>

<p>Crowded buses add open windows and road dust to the same problem. Once the grafts are secure, usually after about ten days, ordinary travel becomes far less of a concern; the clinic will confirm when you have reached that point.</p>

<h2 id="summer-heat-and-the-loo">Summer: heat, sweat and the loo</h2>

<p>The heat builds from April, and May and June bring hot, dry afternoon winds that turn any errand into a sweat-soaked one. Sweat softens crusts before they are ready to come away and makes the area itch, and the urge to scratch is what actually threatens grafts. The new skin over the recipient area is also unusually sensitive to sun for several weeks.</p>

<ul>
  <li>Keep outdoor time to early morning and after dark for the first two weeks, and spend afternoons in a cool room. Air conditioning helps, because it stops you sweating.</li>
  <li>Shade comes from timing rather than fabric: no cap until the clinic clears a loose one, commonly from around ten days.</li>
  <li>If sweat soaks the scalp, do not towel it. Let it dry, and leave cleaning to the scheduled wash or the spray you were given.</li>
</ul>

<p>The monsoon, roughly July to September, adds two things. Waterlogged roads mean splashed water, one more reason to avoid open transport early on. And warm, damp weeks make small tender bumps around emerging hairs (folliculitis) more likely in the months after a transplant. They usually settle with treatment, but show them to the clinic rather than squeezing them, because picking at one can take the graft inside it.</p>

<h2 id="the-smog-season">The smog season: late October to January</h2>

<p>Delhi's air is usually at its worst from late October into January, when crop-residue smoke, traffic emissions, firecrackers and still winter air combine. A fresh recipient area is, in effect, hundreds of tiny healing wounds, and grime settling on them irritates. Pollution is not known to stop grafts taking; the concern is cleanliness and itching.</p>

<ul>
  <li>Stay indoors on the worst days, in the room with an air purifier if you have one.</li>
  <li>A mask protects your lungs and is fine to wear, but pick one with ear loops. Elastic straps around the back of the head sit right across the donor area.</li>
  <li>Keep away from firecracker smoke, sparks and ash around Diwali in the first weeks.</li>
  <li>Resist the woollen cap until the clinic clears a loose, smooth-lined one; knitted caps grip and shed fibres into crusts.</li>
  <li>Room heaters dry the air and make crusts itch. Ask the clinic before putting anything of your own on the recipient area.</li>
</ul>

<p>For all that, winter is the season with the least sweat, which is why many people choose it. The trade is smog for heat.</p>

